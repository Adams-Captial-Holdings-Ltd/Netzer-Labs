/**
 * Hand-rolled YAML writer for `claudeclaw.config.yaml`.
 *
 * We avoid a yaml dependency here because the schema is small and fixed.
 * If the schema grows beyond ~3 nested levels, swap to `js-yaml`.
 */

export interface ClaudeClawConfig {
  version: number;
  stack: string;
  region: string;
  account: string;
  tier: 0 | 1 | 2 | 3;
  ecr: {
    repo: string;
  };
  bedrock: {
    opus?: string;
    sonnet: string;
    haiku: string;
  };
  adapters: {
    slack: boolean;
    telegram: boolean;
  };
  dashboard: {
    token_hint: string;
  };
  config_dir: string;
  agents: string[];
}

export function renderConfigYaml(cfg: ClaudeClawConfig): string {
  const lines: string[] = [
    '# ClaudeClaw Enterprise · workspace config',
    '# Generated by `npm run setup`. Safe to commit.',
    `# Last updated: ${new Date().toISOString()}`,
    '',
    `version: ${cfg.version}`,
    `stack: ${quote(cfg.stack)}`,
    `region: ${quote(cfg.region)}`,
    `account: ${quote(cfg.account)}`,
    `tier: ${cfg.tier}`,
    '',
    'ecr:',
    `  repo: ${quote(cfg.ecr.repo)}`,
    '',
    'bedrock:',
  ];
  if (cfg.bedrock.opus) lines.push(`  opus: ${quote(cfg.bedrock.opus)}`);
  lines.push(`  sonnet: ${quote(cfg.bedrock.sonnet)}`);
  lines.push(`  haiku: ${quote(cfg.bedrock.haiku)}`);
  lines.push('');
  lines.push('adapters:');
  lines.push(`  slack: ${cfg.adapters.slack}`);
  lines.push(`  telegram: ${cfg.adapters.telegram}`);
  lines.push('');
  lines.push('dashboard:');
  lines.push(`  token_hint: ${quote(cfg.dashboard.token_hint)}`);
  lines.push('');
  lines.push(`config_dir: ${quote(cfg.config_dir)}`);
  lines.push('');
  lines.push('# Agents are discovered from $config_dir/agents/ at runtime.');
  lines.push(`agents:${cfg.agents.length === 0 ? ' []' : ''}`);
  cfg.agents.forEach((a) => lines.push(`  - ${quote(a)}`));
  return lines.join('\n') + '\n';
}

function quote(s: string): string {
  // Quote when content contains anything outside [a-zA-Z0-9_-.:/]
  if (/^[a-zA-Z0-9_\-./: ]+$/.test(s) && !s.includes(' ')) return s;
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}
